"""Render a published version as Word, Markdown and JSON.

Word / Google Doc is the copy people read and share. JSON (one entry = one chunk, with category, labels and
source URL as metadata) is what the chatbot should index; Markdown is the same content for anything text based.
"""
from __future__ import annotations

import io
import re
from itertools import groupby

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.opc.constants import RELATIONSHIP_TYPE
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Pt, RGBColor

LINK = re.compile(r"\[([^\]]+)\]\((https?://[^)\s]+)\)")
NUM = re.compile(r"^(\s*)(\d+)\. ")


def blocks(content: str) -> list[dict]:
    """Group body lines into paragraphs, bullets, steps and tables."""
    out: list[dict] = []
    lines = content.split("\n")
    i = 0
    while i < len(lines):
        ln = lines[i]
        if " | " in ln:
            rows = []
            while i < len(lines) and " | " in lines[i]:
                rows.append([c.strip() for c in lines[i].split(" | ")])
                i += 1
            if len(rows) > 1 and len({len(r) for r in rows}) == 1:
                out.append({"type": "table", "rows": rows})
            else:
                out += [{"type": "p", "text": " | ".join(r)} for r in rows]
            continue
        indent = (len(ln) - len(ln.lstrip(" "))) // 2
        s = ln.strip()
        if s.startswith("- "):
            out.append({"type": "bullet", "text": s[2:], "indent": indent})
        elif NUM.match(s):
            out.append({"type": "step", "text": s, "indent": indent})
        elif s:
            out.append({"type": "p", "text": s})
        i += 1
    return out


def _hyperlink(p, text: str, url: str) -> None:
    rid = p.part.relate_to(url, RELATIONSHIP_TYPE.HYPERLINK, is_external=True)
    h = OxmlElement("w:hyperlink")
    h.set(qn("r:id"), rid)
    r = OxmlElement("w:r")
    rpr = OxmlElement("w:rPr")
    for tag, val in (("w:color", "1155CC"), ("w:u", "single")):
        el = OxmlElement(tag)
        el.set(qn("w:val"), val)
        rpr.append(el)
    r.append(rpr)
    t = OxmlElement("w:t")
    t.text = text
    t.set(qn("xml:space"), "preserve")
    r.append(t)
    h.append(r)
    p._p.append(h)


def _fill(p, text: str) -> None:
    pos = 0
    for m in LINK.finditer(text):
        if m.start() > pos:
            p.add_run(text[pos:m.start()])
        _hyperlink(p, m.group(1), m.group(2))
        pos = m.end()
    if pos < len(text):
        p.add_run(text[pos:])


def build_docx(bot_name: str, version: int, published: str, items: list[dict]) -> bytes:
    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(11)
    doc.add_heading(f"{bot_name} Knowledge Base", 0)
    meta = doc.add_paragraph()
    r = meta.add_run(f"Version {version} · Published {published} · {len(items)} entries · Generated by KB Curation. "
                     "Do not edit this document directly: make changes in the Review step so they are tracked.")
    r.italic, r.font.size, r.font.color.rgb = True, Pt(9), RGBColor(0x66, 0x66, 0x66)
    for cat, group in groupby(items, key=lambda x: x["category"]):
        doc.add_heading(cat, 1)
        for it in group:
            doc.add_heading(it["title"], 2)
            for b in blocks(it["content"]):
                if b["type"] == "table":
                    cols = len(b["rows"][0])
                    t = doc.add_table(rows=0, cols=cols)
                    t.style = "Table Grid"
                    for ri, row in enumerate(b["rows"]):
                        cells = t.add_row().cells
                        for ci, val in enumerate(row):
                            cells[ci].paragraphs[0].text = ""
                            _fill(cells[ci].paragraphs[0], val)
                            if ri == 0:
                                for run in cells[ci].paragraphs[0].runs:
                                    run.bold = True
                    doc.add_paragraph()
                elif b["type"] == "bullet":
                    p = doc.add_paragraph(style="List Bullet 2" if b["indent"] else "List Bullet")
                    _fill(p, b["text"])
                elif b["type"] == "step":
                    p = doc.add_paragraph()
                    p.paragraph_format.left_indent = Pt(18 * (1 + b["indent"]))
                    _fill(p, b["text"])
                else:
                    _fill(doc.add_paragraph(), b["text"])
            foot = []
            if it.get("source_url"):
                foot.append(("Source: ", it["source_url"]))
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            if it.get("source_url"):
                run = p.add_run("Source: ")
                run.italic, run.font.size = True, Pt(9)
                _hyperlink(p, it["source_url"], it["source_url"])
            if it.get("secondary"):
                run = p.add_run(("   " if it.get("source_url") else "") + "Also relevant to: " + ", ".join(it["secondary"]))
                run.italic, run.font.size = True, Pt(9)
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def _md_body(content: str) -> str:
    out = []
    for b in blocks(content):
        if b["type"] == "table":
            rows = b["rows"]
            out.append("| " + " | ".join(rows[0]) + " |")
            out.append("|" + " --- |" * len(rows[0]))
            out += ["| " + " | ".join(r) + " |" for r in rows[1:]]
            out.append("")
        elif b["type"] == "bullet":
            out.append("  " * b["indent"] + "- " + b["text"])
        elif b["type"] == "step":
            out.append("  " * b["indent"] + b["text"])
        else:
            out += [b["text"], ""]
    return "\n".join(out).strip()


def build_markdown(bot_name: str, version: int, published: str, items: list[dict]) -> str:
    out = [f"# {bot_name} Knowledge Base", "", f"> Version {version} · Published {published} · {len(items)} entries", ""]
    for cat, group in groupby(items, key=lambda x: x["category"]):
        out += [f"## {cat}", ""]
        for it in group:
            out += [f"### {it['title']}", "", _md_body(it["content"]), ""]
            tail = []
            if it.get("source_url"):
                tail.append(f"Source: <{it['source_url']}>")
            if it.get("secondary"):
                tail.append("Also relevant to: " + ", ".join(it["secondary"]))
            if it.get("labels"):
                tail.append("Labels: " + ", ".join(it["labels"]))
            out += ["  \n".join(tail), ""] if tail else []
    return "\n".join(out)


def build_json(bot_key: str, bot_name: str, version: int, published: str, items: list[dict]) -> dict:
    return {
        "chatbot": bot_key, "name": bot_name, "version": version, "published_at": published,
        "entries": [{
            "id": f"{bot_key}-{it['entry_id']}", "title": it["title"], "category": it["category"],
            "also_in": it.get("secondary", []), "labels": it.get("labels", []), "source_url": it.get("source_url"),
            "content": _md_body(it["content"]),
            "text": f"{it['category']} › {it['title']}\n\n{_md_body(it['content'])}",
        } for it in items],
    }
